export type Key = keyof typeof en

type SourceReasonKey = Extract<Key, `sources.reason.${string}`>

export function sourceReasonKey(code?: string, fallback: SourceReasonKey = 'sources.reason.stream_failed'): SourceReasonKey {
  const key = `sources.reason.${code}`
  return Object.prototype.hasOwnProperty.call(en, key) ? key as SourceReasonKey : fallback
}

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
}

const Ctx = createContext<I18nCtx | null>(null)

const dicts: Record<Lang, Record<string, string>> = { en, zh }

function detectLang(): Lang {
  const stored = localStorage.getItem('infer_lang')
  if (stored === 'en' || stored === 'zh') return stored as Lang
  return navigator.language.startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang)

  const setLang = (l: Lang) => {
    localStorage.setItem('infer_lang', l)
    setLangState(l)
  }

  const t = (key: Key, vars?: Record<string, string | number>): string => {
    let str: string = dicts[lang][key] ?? dicts.en[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replaceAll(`{${k}}`, String(v))
      }
    }
    return str
  }

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useT() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useT must be used within I18nProvider')
  return ctx
}
