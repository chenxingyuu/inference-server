// extractZip extracts a zip archive to destDir.
func extractZip(src string, destDir string) error {
	r, err := zip.OpenReader(src)
	if err != nil {
		return err
	}
	defer r.Close()
	for _, f := range r.File {
		if err := extractZipFile(f, destDir); err != nil {
			return err
		}
	}
	return nil
}

func extractZipFile(f *zip.File, destDir string) error {
	path := filepath.Join(destDir, filepath.FromSlash(f.Name))
	if !strings.HasPrefix(path, filepath.Clean(destDir)+string(os.PathSeparator)) {
		return fmt.Errorf("zip: illegal file path %q", f.Name)
	}
	if f.FileInfo().IsDir() {
		return os.MkdirAll(path, 0o755)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	rc, err := f.Open()
	if err != nil {
		return err
	}
	defer rc.Close()
	out, err := os.Create(path)
	if err != nil {
		return err
	}
	defer out.Close()
	_, err = io.Copy(out, rc) //nolint:gosec // archive from trusted upload
	return err
}

// extractTarGz extracts a .tar.gz archive to destDir.
func extractTarGz(src string, destDir string) error {
	f, err := os.Open(src)
	if err != nil {
		return err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		path := filepath.Join(destDir, filepath.FromSlash(hdr.Name))
		if !strings.HasPrefix(path, filepath.Clean(destDir)+string(os.PathSeparator)) {
			return fmt.Errorf("tar: illegal file path %q", hdr.Name)
		}
		switch hdr.Typeflag {
		case tar.TypeDir:
			if err := os.MkdirAll(path, 0o755); err != nil {
				return err
			}
		case tar.TypeReg:
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				return err
			}
			out, err := os.Create(path)
			if err != nil {
				return err
			}
			_, copyErr := io.Copy(out, tr) //nolint:gosec
			out.Close()
			if copyErr != nil {
				return copyErr
			}
		}
	}
	return nil
}

var omBatchPattern = regexp.MustCompile(`model_b(\d+)\.om$`)

// scanArchiveDir walks tmpDir and returns detected backend, file manifest, and parsed config.
func scanArchiveDir(tmpDir string) (backend string, omFiles map[int]string, modelFile string, cfg *archiveConfig, filesFound []string, suggestedID string, err error) {
	omFiles = make(map[int]string)

	// Check if there's a single top-level directory (use its name as suggested ID).
	entries, readErr := os.ReadDir(tmpDir)
	if readErr == nil && len(entries) == 1 && entries[0].IsDir() {
		suggestedID = entries[0].Name()
	}

	err = filepath.Walk(tmpDir, func(path string, info os.FileInfo, walkErr error) error {
		if walkErr != nil || info.IsDir() {
			return walkErr
		}
		base := filepath.Base(path)
		rel, _ := filepath.Rel(tmpDir, path)
		filesFound = append(filesFound, rel)

		switch {
		case base == "config.yaml":
			data, readErr := os.ReadFile(path)
			if readErr != nil {
				return nil
			}
			cfg = &archiveConfig{}
			if parseErr := yaml.Unmarshal(data, cfg); parseErr != nil {
				cfg = nil
			}
		case strings.HasSuffix(base, ".om"):
			if m := omBatchPattern.FindStringSubmatch(base); m != nil {
				n, _ := strconv.Atoi(m[1])
				omFiles[n] = path
			} else if len(omFiles) < 4 {
				// Non-standard filename: assign to the next available slot.
				for _, slot := range []int{1, 4, 8, 16} {
					if _, exists := omFiles[slot]; !exists {
						omFiles[slot] = path
						break
					}
				}
			}
		case strings.HasSuffix(base, ".engine"):
			if modelFile == "" {
				modelFile = path
			}
		case strings.HasSuffix(base, ".onnx"):
			if modelFile == "" {
				modelFile = path
			}
		}
		return nil
	})
	if err != nil {
		return
	}

	// Detect backend.
	hasOM := len(omFiles) > 0
	hasEngine := modelFile != "" && strings.HasSuffix(modelFile, ".engine")
	hasOnnx := modelFile != "" && strings.HasSuffix(modelFile, ".onnx")
	// Prefer config.yaml backend if present.
	if cfg != nil && cfg.Backend != "" {
		backend = cfg.Backend
	} else if hasOM {
		backend = "ascend"
	} else if hasEngine {
		backend = "trt"
	} else if hasOnnx {
		backend = "cpu"
	}

	// Validate: no mixing.
	if hasOM && (hasEngine || hasOnnx) {
		err = fmt.Errorf("mixed backend files detected in archive")
	}
	return
}

// copyFile copies src to dst, creating dst if needed.
func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()
	_, err = io.Copy(out, in)
	return err
}

// renameOrCopy tries os.Rename; falls back to copy+remove on cross-device links.
func renameOrCopy(src, dst string) error {
	if err := os.Rename(src, dst); err == nil {
		return nil
	}
	if err := copyFile(src, dst); err != nil {
		return err
	}
	return os.Remove(src)
}

func envOr(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func corsMiddleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		c.Header("Access-Control-Allow-Origin", "*")
		c.Header("Access-Control-Allow-Methods", "GET, POST, DELETE, OPTIONS")
		c.Header("Access-Control-Allow-Headers", "Authorization, Content-Type")
		if c.Request.Method == http.MethodOptions {
			c.AbortWithStatus(http.StatusNoContent)
			return
		}
		c.Next()
	}
}

func authMiddleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		bearer := c.GetHeader("Authorization")
		if !strings.HasPrefix(bearer, "Bearer ") || strings.TrimPrefix(bearer, "Bearer ") != apiKey {
			c.AbortWithStatusJSON(http.StatusUnauthorized, ErrorResponse{
				Status:  "error",
				Code:    "unauthorized",
				Message: "missing or invalid API key",
			})
			return
		}
		c.Next()
	}
}

// callFn is the engine communication function; replaceable in tests.
var callFn = func(cmd map[string]any) (map[string]any, error) {
	conn, err := net.Dial("unix", socketPath)
	if err != nil {
		return nil, err
	}
	defer conn.Close()

	data, err := json.Marshal(cmd)
	if err != nil {
		return nil, fmt.Errorf("marshal request: %w", err)
	}
	fmt.Fprintf(conn, "%s\n", data)

	var resp map[string]any
	if err := json.NewDecoder(bufio.NewReader(conn)).Decode(&resp); err != nil {
		return nil, err
	}
	return resp, nil
}

func call(cmd map[string]any) (map[string]any, error) { return callFn(cmd) }

