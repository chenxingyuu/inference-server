func envOr(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func corsMiddleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		c.Header("Access-Control-Allow-Origin", "*")
		c.Header("Access-Control-Allow-Methods", "GET, POST, DELETE, OPTIONS")
		c.Header("Access-Control-Allow-Headers", "Authorization, Content-Type")
		if c.Request.Method == http.MethodOptions {
			c.AbortWithStatus(http.StatusNoContent)
			return
		}
		c.Next()
	}
}

func authMiddleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		bearer := c.GetHeader("Authorization")
		if !strings.HasPrefix(bearer, "Bearer ") || strings.TrimPrefix(bearer, "Bearer ") != apiKey {
			c.AbortWithStatusJSON(http.StatusUnauthorized, ErrorResponse{
				Status:  "error",
				Code:    "unauthorized",
				Message: "missing or invalid API key",
			})
			return
		}
		c.Next()
	}
}

// callFn is the engine communication function; replaceable in tests.
var callFn = func(cmd map[string]any) (map[string]any, error) {
	conn, err := net.Dial("unix", socketPath)
	if err != nil {
		return nil, err
	}
	defer conn.Close()

	data, err := json.Marshal(cmd)
	if err != nil {
		return nil, fmt.Errorf("marshal request: %w", err)
	}
	fmt.Fprintf(conn, "%s\n", data)

	var resp map[string]any
	if err := json.NewDecoder(bufio.NewReader(conn)).Decode(&resp); err != nil {
		return nil, err
	}
	return resp, nil
}

func call(cmd map[string]any) (map[string]any, error) { return callFn(cmd) }

func engineUnavailable(c *gin.Context, err error) {
	c.String(http.StatusServiceUnavailable, err.Error())
}

// handleHealthz godoc
//
//	@Summary	Health check
//	@Tags		health
//	@Produce	plain
//	@Success	200	{string}	string	"OK"
//	@Failure	503	{string}	string	"engine unreachable"
//	@Router		/healthz [get]
func handleHealthz(c *gin.Context) {
	resp, err := call(map[string]any{"cmd": "health"})
	if err != nil {
		engineUnavailable(c, err)
		return
	}
	if resp["status"] != "ok" {
		c.JSON(http.StatusServiceUnavailable, resp)
		return
	}
	c.String(http.StatusOK, "OK")
}

