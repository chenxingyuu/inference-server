// handleTaskAction godoc
//
//	@Summary	Start or stop a task
//	@Tags		tasks
//	@Produce	json
//	@Security	ApiKeyAuth
//	@Param		id		path		string	true	"Task ID"
//	@Param		action	path		string	true	"Action"	Enums(start, stop)
//	@Success	200		{object}	OkResponse
//	@Failure	401		{object}	ErrorResponse
//	@Failure	404		{object}	ErrorResponse
//	@Failure	503		{string}	string	"engine unreachable"
//	@Router		/tasks/{id}/{action} [post]
func handleTaskAction(c *gin.Context) {
	id := c.Param("id")
	action := c.Param("action")
	if action != "start" && action != "stop" {
		c.Status(http.StatusNotFound)
		return
	}
	resp, err := call(map[string]any{"cmd": action + "_task", "id": id})
	if err != nil {
		engineUnavailable(c, err)
		return
	}
	if resp["status"] == "ok" {
		_ = store.SetTaskRunning(id, action == "start")
	}
	code := http.StatusOK
	if resp["status"] != "ok" {
		code = http.StatusNotFound
	}
	c.JSON(code, resp)
}

func callDelete(c *gin.Context, cmd string, onSuccess func(id string)) {
	id := c.Param("id")
	resp, err := call(map[string]any{"cmd": cmd, "id": id})
	if err != nil {
		engineUnavailable(c, err)
		return
	}
	if resp["status"] == "ok" && onSuccess != nil {
		onSuccess(id)
	}
	code := http.StatusOK
	if resp["status"] != "ok" {
		if resp["code"] == "in_use" {
			code = http.StatusConflict
		} else {
			code = http.StatusNotFound
		}
	}
	c.JSON(code, resp)
}

func main() {
	if apiKey == "" {
		fmt.Fprintln(os.Stderr, "WARNING: INFER_API_KEY not set; management endpoints are unprotected")
	}

	var err error
	store, err = NewStore(statePath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "state store init:", err)
		os.Exit(1)
	}
	go func() {
		if err := replayState(store.Snapshot(), callFn, 30, 2*time.Second); err != nil {
			fmt.Fprintln(os.Stderr, "WARNING: state replay incomplete:", err)
		}
	}()

	r := gin.Default()
	r.Use(corsMiddleware())

	// Public: health probe, metrics scrape, API docs.
	r.GET("/healthz", handleHealthz)
	r.GET("/metrics", handleMetrics)
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// Protected management endpoints.
	api := r.Group("/")
	if apiKey != "" {
		api.Use(authMiddleware())
	}

	api.GET("/sources", handleListSources)
	api.POST("/sources", handleAddSource)
	api.DELETE("/sources/:id", handleRemoveSource)

	api.GET("/pipelines", handleListPipelines)
	api.POST("/pipelines", handleAddPipeline)
	api.PUT("/pipelines/:id", handleUpdatePipeline)
	api.DELETE("/pipelines/:id", handleRemovePipeline)

	api.GET("/models", handleListModels)
	api.POST("/models", handleLoadModel)
	api.DELETE("/models/:id", handleUnloadModel)

	api.GET("/tasks", handleListTasks)
	api.POST("/tasks", handleAddTask)
	api.DELETE("/tasks/:id", handleRemoveTask)
	api.POST("/tasks/:id/:action", handleTaskAction)

	fmt.Printf("infer-server listening on %s (socket: %s)\n", listenAddr, socketPath)
	if err := r.Run(listenAddr); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
