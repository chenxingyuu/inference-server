type pendingUpload struct {
	tmpDir    string
	backend   string
	omFiles   map[int]string // batch_size → abs path (ascend)
	modelFile string         // abs path of .engine / .onnx (trt/cpu)
	expiresAt time.Time
}

var pendingUploads sync.Map // token(string) → pendingUpload

func startTokenCleanup() {
	go func() {
		for range time.Tick(5 * time.Minute) {
			now := time.Now()
			pendingUploads.Range(func(k, v any) bool {
				entry := v.(pendingUpload)
				if now.After(entry.expiresAt) {
					os.RemoveAll(entry.tmpDir)
					pendingUploads.Delete(k)
				}
				return true
			})
		}
	}()
}

func newToken() string {
	b := make([]byte, 16)
	rand.Read(b) //nolint:errcheck // crypto/rand.Read never returns error on supported platforms
	return fmt.Sprintf("%x", b)
}

