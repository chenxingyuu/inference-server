// handleAnalyzeArchive godoc
//
//	@Summary		Analyze a model archive (.zip or .tar.gz)
//	@Description	Extracts the archive, detects backend and model files, parses config.yaml if present.
//	@Description	Returns a token valid for 10 minutes. Submit the token to POST /models/upload to deploy.
//	@Tags			models
//	@Accept			multipart/form-data
//	@Produce		json
//	@Security		ApiKeyAuth
//	@Param			archive	formData	file	true	"Archive file (.zip or .tar.gz)"
//	@Success		200		{object}	ArchiveAnalysisResponse
//	@Failure		400		{object}	ErrorResponse
//	@Failure		401		{object}	ErrorResponse
//	@Router			/models/upload/analyze [post]
func handleAnalyzeArchive(c *gin.Context) {
	if modelRepositoryPath == "" {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "no_repository",
			Message: "MODEL_REPOSITORY env var not set"})
		return
	}

	archiveFile, err := c.FormFile("archive")
	if err != nil {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
			Message: "archive field required"})
		return
	}

	name := strings.ToLower(archiveFile.Filename)
	isTarGz := strings.HasSuffix(name, ".tar.gz") || strings.HasSuffix(name, ".tgz")
	isZip := strings.HasSuffix(name, ".zip")
	if !isTarGz && !isZip {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "unsupported_format",
			Message: "archive must be .zip or .tar.gz"})
		return
	}

	// Save multipart file to a temp file so we can open it as a reader.
	tmpFile, err := os.CreateTemp("", "infer-archive-*")
	if err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to create temp file"})
		return
	}
	tmpFilePath := tmpFile.Name()
	defer os.Remove(tmpFilePath)
	tmpFile.Close()

	if err := c.SaveUploadedFile(archiveFile, tmpFilePath); err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to save archive"})
		return
	}

	// Extract to a temp directory.
	tmpDir, err := os.MkdirTemp("", "infer-upload-*")
	if err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to create temp directory"})
		return
	}

	if isZip {
		err = extractZip(tmpFilePath, tmpDir)
	} else {
		err = extractTarGz(tmpFilePath, tmpDir)
	}
	if err != nil {
		os.RemoveAll(tmpDir)
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "extract_error",
			Message: "failed to extract archive: " + err.Error()})
		return
	}

	backend, omFiles, modelFile, cfg, filesFound, suggestedID, err := scanArchiveDir(tmpDir)
	if err != nil {
		os.RemoveAll(tmpDir)
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "scan_error",
			Message: err.Error()})
		return
	}
	if backend == "" {
		os.RemoveAll(tmpDir)
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "no_model_files",
			Message: "no model files (.om / .engine / .onnx) found in archive"})
		return
	}

	// Build response from config.yaml (if any) or defaults.
	resp := ArchiveAnalysisResponse{
		Backend:       backend,
		YoloVersion:   "v8",
		ModelType:     "detector",
		BatchSize:     1,
		ConfThresh:    0.25,
		NmsThresh:     0.45,
		NumClasses:    80,
		InstanceCount: 1,
		FilesFound:    filesFound,
		SuggestedID:   suggestedID,
	}
	if cfg != nil {
		resp.HasConfig = true
		if cfg.Version != "" {
			resp.YoloVersion = cfg.Version
		}
		if cfg.ModelType != "" {
			resp.ModelType = cfg.ModelType
		}
		if cfg.BatchSize > 0 {
			resp.BatchSize = cfg.BatchSize
		}
		if cfg.ConfThresh > 0 {
			resp.ConfThresh = cfg.ConfThresh
		}
		if cfg.NmsThresh > 0 {
			resp.NmsThresh = cfg.NmsThresh
		}
		if cfg.NumClasses > 0 {
			resp.NumClasses = cfg.NumClasses
		}
		if cfg.InstanceCount > 0 {
			resp.InstanceCount = cfg.InstanceCount
		}
	}
	if backend == "ascend" {
		maxBatch := 1
		for b := range omFiles {
			if b > maxBatch {
				maxBatch = b
			}
		}
		if resp.BatchSize < maxBatch {
			resp.BatchSize = maxBatch
		}
	}

	token := newToken()
	resp.Token = token
	pendingUploads.Store(token, pendingUpload{
		tmpDir:    tmpDir,
		backend:   backend,
		omFiles:   omFiles,
		modelFile: modelFile,
		expiresAt: time.Now().Add(10 * time.Minute),
	})

	c.JSON(http.StatusOK, resp)
}

// handleDeployFromToken deploys a model from a previously analyzed archive (token-based path).
func handleDeployFromToken(c *gin.Context, token string) {
	v, ok := pendingUploads.Load(token)
	if !ok {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "token_expired",
			Message: "token not found or expired; re-analyze the archive"})
		return
	}
	entry := v.(pendingUpload)
	if time.Now().After(entry.expiresAt) {
		pendingUploads.Delete(token)
		os.RemoveAll(entry.tmpDir)
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "token_expired",
			Message: "token not found or expired; re-analyze the archive"})
		return
	}

	id := c.PostForm("id")
	if !modelIDPattern.MatchString(id) {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "invalid_id",
			Message: "id must match ^[A-Za-z0-9_-]+$"})
		return
	}

	modelDir := filepath.Join(modelRepositoryPath, id)
	if _, err := os.Stat(modelDir); err == nil {
		c.JSON(http.StatusConflict, ErrorResponse{Status: "error", Code: "already_exists",
			Message: "model '" + id + "' already exists in repository"})
		return
	}

	backend := c.DefaultPostForm("backend", entry.backend)
	yoloVersion := c.DefaultPostForm("yolo_version", "v8")
	modelType := c.DefaultPostForm("model_type", "detector")
	batchSize, _ := strconv.Atoi(c.DefaultPostForm("batch_size", "1"))
	if batchSize < 1 {
		batchSize = 1
	}
	confThresh, _ := strconv.ParseFloat(c.DefaultPostForm("conf_thresh", "0.25"), 64)
	nmsThresh, _ := strconv.ParseFloat(c.DefaultPostForm("nms_thresh", "0.45"), 64)
	numClasses, _ := strconv.Atoi(c.DefaultPostForm("num_classes", "80"))
	instanceCount, _ := strconv.Atoi(c.DefaultPostForm("instance_count", "1"))
	if instanceCount < 1 {
		instanceCount = 1
	}

	versionDir := filepath.Join(modelDir, "1")
	if err := os.MkdirAll(versionDir, 0o755); err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to create model directory"})
		return
	}

	var configYAML string
	switch backend {
	case "ascend":
		if len(entry.omFiles) == 0 {
			os.RemoveAll(modelDir)
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "no .om files in analyzed archive"})
			return
		}
		var omPathsYAML strings.Builder
		omPathsYAML.WriteString("om_paths:\n")
		maxBatch := 1
		for batch, srcPath := range entry.omFiles {
			destName := fmt.Sprintf("model_b%d.om", batch)
			if err := renameOrCopy(srcPath, filepath.Join(versionDir, destName)); err != nil {
				os.RemoveAll(modelDir)
				c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
					Message: "failed to move om file"})
				return
			}
			fmt.Fprintf(&omPathsYAML, "  %d: %s\n", batch, destName)
			if batch > maxBatch {
				maxBatch = batch
			}
		}
		if batchSize < maxBatch {
			batchSize = maxBatch
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: ascend\nbatch_size: %d\n%s"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, omPathsYAML.String(), confThresh, nmsThresh, numClasses, modelType, instanceCount)

	case "trt":
		if entry.modelFile == "" {
			os.RemoveAll(modelDir)
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "no .engine file in analyzed archive"})
			return
		}
		destName := id + ".engine"
		if err := renameOrCopy(entry.modelFile, filepath.Join(versionDir, destName)); err != nil {
			os.RemoveAll(modelDir)
			c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
				Message: "failed to move engine file"})
			return
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: trt\nbatch_size: %d\nengine_path: %s\n"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, destName, confThresh, nmsThresh, numClasses, modelType, instanceCount)

	case "cpu":
		if entry.modelFile == "" {
			os.RemoveAll(modelDir)
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "no .onnx file in analyzed archive"})
			return
		}
		destName := id + ".onnx"
		if err := renameOrCopy(entry.modelFile, filepath.Join(versionDir, destName)); err != nil {
			os.RemoveAll(modelDir)
			c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
				Message: "failed to move onnx file"})
			return
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: cpu\nbatch_size: %d\nonnx_path: %s\n"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, destName, confThresh, nmsThresh, numClasses, modelType, instanceCount)

	default:
		os.RemoveAll(modelDir)
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "invalid_backend",
			Message: "backend must be one of: cpu, trt, ascend"})
		return
	}

	if err := os.WriteFile(filepath.Join(modelDir, "config.yaml"), []byte(configYAML), 0o644); err != nil {
		os.RemoveAll(modelDir)
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to write config.yaml"})
		return
	}

	resp, err := call(map[string]any{"cmd": "load_from_repository", "id": id})
	if err != nil {
		engineUnavailable(c, err)
		return
	}
	if resp["status"] != "ok" {
		c.JSON(http.StatusBadRequest, resp)
		return
	}

	pendingUploads.Delete(token)
	os.RemoveAll(entry.tmpDir)
	c.JSON(http.StatusCreated, OkResponse{Status: "ok", ID: id})
}

// handleUploadModel godoc
//
//	@Summary		Upload model weights and auto-load
//	@Description	Accepts multipart/form-data. Server generates config.yaml from form fields.
//	@Description	For Ascend: supply batch_1 file (required) and batch_4/batch_8/batch_16 (optional).
//	@Description	Alternatively, supply a token from POST /models/upload/analyze to deploy a previously analyzed archive.
//	@Description	For TRT: supply engine file. For CPU: supply onnx file.
//	@Tags			models
//	@Accept			mpfd
//	@Produce		json
//	@Security		ApiKeyAuth
//	@Param			id				formData	string	true	"Model ID (^[A-Za-z0-9_-]+$)"
//	@Param			backend			formData	string	true	"Backend"			Enums(cpu, trt, ascend)
//	@Param			yolo_version	formData	string	false	"YOLO version"		Enums(v5, v8, v11, v26)
//	@Param			model_type		formData	string	false	"Model type"		Enums(detector, classifier)
//	@Param			batch_size		formData	int		false	"Max batch size"
//	@Param			conf_thresh		formData	number	false	"Confidence threshold"
//	@Param			nms_thresh		formData	number	false	"NMS threshold"
//	@Param			num_classes		formData	int		false	"Number of classes"
//	@Param			instance_count	formData	int		false	"Worker instances"
//	@Param			engine			formData	file	false	"TRT .engine file"
//	@Param			onnx			formData	file	false	"ONNX .onnx file"
//	@Param			batch_1			formData	file	false	"Ascend .om for batch=1 (required for Ascend)"
//	@Param			batch_4			formData	file	false	"Ascend .om for batch=4"
//	@Param			batch_8			formData	file	false	"Ascend .om for batch=8"
//	@Param			batch_16		formData	file	false	"Ascend .om for batch=16"
//	@Success		201	{object}	OkResponse
//	@Failure		400	{object}	ErrorResponse
//	@Failure		401	{object}	ErrorResponse
//	@Failure		409	{object}	ErrorResponse	"model ID already exists in repository"
//	@Failure		500	{object}	ErrorResponse
//	@Failure		503	{string}	string	"engine unreachable"
//	@Router			/models/upload [post]
func handleUploadModel(c *gin.Context) {
	if modelRepositoryPath == "" {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "no_repository",
			Message: "MODEL_REPOSITORY env var not set"})
		return
	}

	// Token-based deploy: use files from a previously analyzed archive.
	if token := c.PostForm("token"); token != "" {
		handleDeployFromToken(c, token)
		return
	}

	id := c.PostForm("id")
	if !modelIDPattern.MatchString(id) {
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "invalid_id",
			Message: "id must match ^[A-Za-z0-9_-]+$"})
		return
	}

	backend := c.DefaultPostForm("backend", "cpu")
	yoloVersion := c.DefaultPostForm("yolo_version", "v8")
	modelType := c.DefaultPostForm("model_type", "detector")
	batchSize, _ := strconv.Atoi(c.DefaultPostForm("batch_size", "1"))
	if batchSize < 1 {
		batchSize = 1
	}
	confThresh, _ := strconv.ParseFloat(c.DefaultPostForm("conf_thresh", "0.25"), 64)
	nmsThresh, _ := strconv.ParseFloat(c.DefaultPostForm("nms_thresh", "0.45"), 64)
	numClasses, _ := strconv.Atoi(c.DefaultPostForm("num_classes", "80"))
	instanceCount, _ := strconv.Atoi(c.DefaultPostForm("instance_count", "1"))
	if instanceCount < 1 {
		instanceCount = 1
	}

	modelDir := filepath.Join(modelRepositoryPath, id)
	if _, err := os.Stat(modelDir); err == nil {
		c.JSON(http.StatusConflict, ErrorResponse{Status: "error", Code: "already_exists",
			Message: "model '" + id + "' already exists in repository"})
		return
	}

	versionDir := filepath.Join(modelDir, "1")
	if err := os.MkdirAll(versionDir, 0o755); err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to create model directory"})
		return
	}

	// Save weight files and build config.yaml content.
	var configYAML string
	switch backend {
	case "trt":
		engineFile, err := c.FormFile("engine")
		if err != nil {
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "engine file required for trt backend"})
			os.RemoveAll(modelDir)
			return
		}
		destName := id + ".engine"
		if err := c.SaveUploadedFile(engineFile, filepath.Join(versionDir, destName)); err != nil {
			c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
				Message: "failed to save engine file"})
			os.RemoveAll(modelDir)
			return
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: trt\nbatch_size: %d\nengine_path: %s\n"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, destName, confThresh, nmsThresh, numClasses, modelType, instanceCount)

	case "cpu":
		onnxFile, err := c.FormFile("onnx")
		if err != nil {
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "onnx file required for cpu backend"})
			os.RemoveAll(modelDir)
			return
		}
		destName := id + ".onnx"
		if err := c.SaveUploadedFile(onnxFile, filepath.Join(versionDir, destName)); err != nil {
			c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
				Message: "failed to save onnx file"})
			os.RemoveAll(modelDir)
			return
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: cpu\nbatch_size: %d\nonnx_path: %s\n"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, destName, confThresh, nmsThresh, numClasses, modelType, instanceCount)

	case "ascend":
		batch1, err := c.FormFile("batch_1")
		if err != nil {
			c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "missing_file",
				Message: "batch_1 file required for ascend backend"})
			os.RemoveAll(modelDir)
			return
		}
		omPaths := []struct {
			batchSize int
			formKey   string
			fileName  string
		}{
			{1, "batch_1", "model_b1.om"},
			{4, "batch_4", "model_b4.om"},
			{8, "batch_8", "model_b8.om"},
			{16, "batch_16", "model_b16.om"},
		}
		_ = batch1 // validated above; saved in the loop below
		var omPathsYAML strings.Builder
		omPathsYAML.WriteString("om_paths:\n")
		maxBatch := 1
		for _, entry := range omPaths {
			f, err := c.FormFile(entry.formKey)
			if err != nil {
				continue // optional except batch_1 (already validated)
			}
			if err := c.SaveUploadedFile(f, filepath.Join(versionDir, entry.fileName)); err != nil {
				c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
					Message: "failed to save " + entry.formKey})
				os.RemoveAll(modelDir)
				return
			}
			fmt.Fprintf(&omPathsYAML, "  %d: %s\n", entry.batchSize, entry.fileName)
			if entry.batchSize > maxBatch {
				maxBatch = entry.batchSize
			}
		}
		if batchSize < maxBatch {
			batchSize = maxBatch
		}
		configYAML = fmt.Sprintf("version: %s\nbackend: ascend\nbatch_size: %d\n%s"+
			"conf_thresh: %g\nnms_thresh: %g\nnum_classes: %d\nmodel_type: %s\ninstance_count: %d\n",
			yoloVersion, batchSize, omPathsYAML.String(), confThresh, nmsThresh, numClasses, modelType, instanceCount)

	default:
		c.JSON(http.StatusBadRequest, ErrorResponse{Status: "error", Code: "invalid_backend",
			Message: "backend must be one of: cpu, trt, ascend"})
		os.RemoveAll(modelDir)
		return
	}

	if err := os.WriteFile(filepath.Join(modelDir, "config.yaml"), []byte(configYAML), 0o644); err != nil {
		c.JSON(http.StatusInternalServerError, ErrorResponse{Status: "error", Code: "io_error",
			Message: "failed to write config.yaml"})
		os.RemoveAll(modelDir)
		return
	}

	resp, err := call(map[string]any{"cmd": "load_from_repository", "id": id})
	if err != nil {
		engineUnavailable(c, err)
		return
	}
	if resp["status"] != "ok" {
		c.JSON(http.StatusBadRequest, resp)
		return
	}
	c.JSON(http.StatusCreated, OkResponse{Status: "ok", ID: id})
}

